async function main() {
  const connection = await mysql.createConnection({
    host: process.env.DB_HOST,
    port: Number(process.env.DB_PORT || 3306),
    user: process.env.DB_USER,
    password: process.env.DB_PASSWORD,
    database: process.env.DB_NAME,
  });

  let created = 0, skipped = 0;
  for (const [date, theme, series] of ENTRIES) {
    const [existing] = await connection.query('SELECT id FROM morning_boost_calendar WHERE boost_date = ?', [date]);
    if (existing.length) {
      skipped++;
      continue;
    }
    await connection.query(
      'INSERT INTO morning_boost_calendar (boost_date, theme, series) VALUES (?, ?, ?)',
      [date, theme, series]
    );
    created++;
  }

  console.log(`Done. Created ${created}, skipped ${skipped}.`);
  await connection.end();
}

main().catch(err => {
  console.error('Seeding morning boost calendar failed:', err.message);
  process.exit(1);
});
