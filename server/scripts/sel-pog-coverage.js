const cell = (v) => (v === 'D' ? 'D' : v === 'S' ? 's' : '');
const count = (games, kind, key, v) => games.filter((g) => g[kind][key] === v).length;

function table(games, kind, keys, names) {
  let out = `| Game | Band | ${keys.join(' | ')} |\n|---|---|${keys.map(() => '---').join('|')}|\n`;
  games.forEach((g) => { out += `| ${g.slug}${g.skills ? ' (skills)' : ''} | ${g.band} | ${keys.map((k) => cell(g[kind][k])).join(' | ')} |\n`; });
  out += `| **Direct (D)** | | ${keys.map((k) => count(games, kind, k, 'D')).join(' | ')} |\n`;
  out += `| **Supporting (s)** | | ${keys.map((k) => count(games, kind, k, 'S')).join(' | ')} |\n`;
  return out;
}
function gaps(games, kind, keys, names) {
  return keys.map((k) => ({ k, d: count(games, kind, k, 'D'), s: count(games, kind, k, 'S') })).filter((x) => x.d < 2)
    .map((x) => `- **${x.k} ${names[x.k]}**: ${x.d} direct, ${x.s} supporting${x.d === 0 && x.s === 0 ? ' (nothing at all)' : ''}`).join('\n');
}

